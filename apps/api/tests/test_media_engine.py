def _request(tmp_path, **kwargs) -> RenderRequest:
    defaults = dict(
        background=tmp_path / "bg.png",
        audio=tmp_path / "a.wav",
        output_path=tmp_path / "out.mp4",
    )
    defaults.update(kwargs)
    return RenderRequest(**defaults)


