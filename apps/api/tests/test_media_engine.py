SAMPLE_PROBE_JSON = {
    "format": {"format_name": "mov,mp4,m4a", "duration": "15.4"},
    "streams": [
        {"codec_type": "video", "codec_name": "h264", "width": 320, "height": 180,
         "avg_frame_rate": "30000/1001"},
        {"codec_type": "audio", "codec_name": "aac", "sample_rate": "22050",
         "channels": 2, "bit_rate": "128000"},
    ],
}


def test_probe_to_model_parses_streams():
    probe = probe_to_model(SAMPLE_PROBE_JSON)
    assert probe.has_video and probe.has_audio
    assert probe.width == 320 and probe.height == 180
    assert abs(probe.fps - 29.97) < 0.01
    assert probe.audio_codec == "aac"
    assert probe.sample_rate == 22050
    assert probe.channels == 2
    assert abs(probe.duration_seconds - 15.4) < 0.01
    assert probe.container_format == "mov,mp4,m4a"


def test_probe_to_model_audio_only():
    probe = probe_to_model({"format": {"format_name": "wav"}, "streams": [
        {"codec_type": "audio", "codec_name": "pcm_s16le", "sample_rate": "44100", "channels": 1},
    ]})
    assert probe.has_audio and not probe.has_video
    assert probe.video_codec is None
    assert probe.sample_rate == 44100


