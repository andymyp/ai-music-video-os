class FakeRunner:
    def __init__(self, ffprobe_json=None, error: Exception | None = None):
        self.calls: list[list[str]] = []
        self.ffprobe_json = ffprobe_json
        self.error = error

    async def __call__(self, cmd, *, timeout=None):
        self.calls.append(cmd)
        if self.error:
            raise self.error
        if self.ffprobe_json is not None:
            return json.dumps(self.ffprobe_json).encode(), b""
        return b"", b""


